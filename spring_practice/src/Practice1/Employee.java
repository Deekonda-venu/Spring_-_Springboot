package Practice1;

public class Employee {

    int EId;
    String Ename;

    public Employee() {
    }

    public Employee(int EId, String Ename) {
        this.EId = EId;
        this.Ename = Ename;
    }
    public int getEId() {
        return EId;
    }

    public void setEId(int EId) {
        this.EId = EId;
    }

    public String getEname() {
        return Ename;
    }

    public void setEname(String Ename) {
        this.Ename = Ename;
    }





}

